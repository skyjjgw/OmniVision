#!/bin/bash
# OmniVision 树莓派端云协同开机自启脚本

# ==========================================
# 1. 基础配置 (请根据树莓派的实际情况修改)
# ==========================================
PROJECT_DIR="/home/pi/OmniVision"   # 你的代码在树莓派上的绝对路径
MAIN_SCRIPT="main.py"               # 你的核心启动程序 (推流+推理的入口文件)
LOG_FILE="$PROJECT_DIR/boot_log.txt" # 开机启动的日志文件，方便排查问题

echo "=========================================" >> $LOG_FILE
echo "系统开机 - 脚本开始执行: $(date)" >> $LOG_FILE

# ==========================================
# 2. 网络连通性死循环检测
# ==========================================
echo "正在检测网络连接..." >> $LOG_FILE
# ping 阿里云的公共 DNS (223.5.5.5) 来验证是否真正连上外网
while ! ping -c 1 -W 2 223.5.5.5 > /dev/null 2>&1; do
    echo "[$(date)] 网络未连通，等待 3 秒后重试..." >> $LOG_FILE
    sleep 3
done
echo "[$(date)] 网络已成功连接！" >> $LOG_FILE

# ==========================================
# 3. 运行环境准备
# ==========================================
cd $PROJECT_DIR
echo "[$(date)] 已进入项目目录: $PROJECT_DIR" >> $LOG_FILE

# 如果你的树莓派使用了 Python 虚拟环境，请取消下面这行的注释并修改路径
# source /home/pi/venv/bin/activate
# echo "[$(date)] 虚拟环境已激活" >> $LOG_FILE

# ==========================================
# 4. 启动核心业务
# ==========================================
echo "[$(date)] 准备启动视觉引擎与推流服务: $MAIN_SCRIPT" >> $LOG_FILE

# 执行 Python 脚本，并将所有输出（正常输出和错误报错）都写入日志文件
python3 $MAIN_SCRIPT >> $LOG_FILE 2>&1
